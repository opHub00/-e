export const PORTFOLIO_UNAVAILABLE_REASONS = [
  'NO_ACTIVE_RULE_SET',
  'NO_LISTING_BINDING',
  'DOCUMENT_MISSING',
  'DOCUMENT_PARSE_FAILED',
  'RULE_EXTRACTION_FAILED',
  'RULE_REVIEW_PENDING',
  'INVALID_RULE_SET',
  'UNSUPPORTED_SCHEMA',
  'UNRESOLVED_CRITICAL_RULE',
  'SOURCE_DOCUMENT_REVALIDATION_REQUIRED',
  'SERVER_REPOSITORY_ERROR',
] as const;

export type PortfolioUnavailableReason = typeof PORTFOLIO_UNAVAILABLE_REASONS[number];
export type PortfolioItemFailureCode = PortfolioUnavailableReason | 'NOT_CALCULATED';

const EXACT_ERROR_MAP: Record<string, PortfolioUnavailableReason> = {
  RULE_NOT_AVAILABLE: 'NO_ACTIVE_RULE_SET',
  NO_ACTIVE_RULE_SET: 'NO_ACTIVE_RULE_SET',
  NO_LISTING_BINDING: 'NO_LISTING_BINDING',
  DOCUMENT_MISSING: 'DOCUMENT_MISSING',
  DOCUMENT_PARSE_FAILED: 'DOCUMENT_PARSE_FAILED',
  RULE_EXTRACTION_FAILED: 'RULE_EXTRACTION_FAILED',
  RULE_REVIEW_PENDING: 'RULE_REVIEW_PENDING',
  INVALID_RULE_SET: 'INVALID_RULE_SET',
  UNSUPPORTED_SCHEMA: 'UNSUPPORTED_SCHEMA',
  UNRESOLVED_CRITICAL_RULE: 'UNRESOLVED_CRITICAL_RULE',
  SOURCE_DOCUMENT_MISMATCH: 'SOURCE_DOCUMENT_REVALIDATION_REQUIRED',
  SOURCE_DOCUMENT_REVALIDATION_REQUIRED: 'SOURCE_DOCUMENT_REVALIDATION_REQUIRED',
};

/** Client-visible failures are stable categories; raw provider/database details stay in server logs. */
export function normalizePortfolioFailure(error: unknown): PortfolioUnavailableReason {
  const raw = error instanceof Error ? error.message : typeof error === 'string' ? error : '';
  return EXACT_ERROR_MAP[raw] ?? 'SERVER_REPOSITORY_ERROR';
}

